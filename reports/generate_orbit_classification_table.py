#!/usr/bin/env python3
from __future__ import annotations

import json
from pathlib import Path

import h5py
import numpy as np
from dasst.functions import ca_criteria


ROOT = Path(__file__).resolve().parents[1]
AU = 1.495978707e11
ORBIT_H5 = ROOT / "products" / "orbit_determination" / "orbit_classification_100.h5"
VERSION_FALLBACK_H5 = ROOT / "products" / "orbit_determination" / "best_fit_orbit.h5"
OUT = ROOT / "reports" / "orbit_classification_table.tex"
MACRO_OUT = ROOT / "reports" / "orbit_classification_macros.tex"


def fmt_prob(value: float) -> str:
    return f"{100.0 * value:.1f}\\%"


def latex_macro(name: str, value: str) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def read_orbit_samples(path: Path) -> tuple[np.ndarray, dict[str, str]]:
    with h5py.File(path, "r") as h:
        kep = np.asarray(h["kepler_HeliocentricMeanEcliptic_final"][()], dtype=float)
        attrs = {
            "trajectory_fit_version": str(h.attrs.get("trajectory_fit_version", "unspecified")),
            "n_samples": str(int(h.attrs.get("n_samples", kep.shape[1]))),
            "seed": str(int(h.attrs.get("seed", 0))),
            "trajectory_json": str(h.attrs.get("trajectory_json", "")),
            "kepler_names": str(h.attrs.get("kepler_names", "")),
        }
    return kep, attrs


def trajectory_version(path: Path) -> str:
    try:
        with h5py.File(path, "r") as h:
            version = str(h.attrs.get("trajectory_fit_version", "unspecified"))
    except Exception:
        version = "unspecified"
    return version


def classify(path: Path) -> tuple[list[dict[str, object]], dict[str, str]]:
    kep, attrs = read_orbit_samples(path)
    if attrs["trajectory_fit_version"] == "unspecified":
        attrs["trajectory_fit_version"] = trajectory_version(VERSION_FALLBACK_H5)
    good = np.all(np.isfinite(kep), axis=0)
    a = kep[0, good] / AU
    e = kep[1, good]
    inc = kep[2, good]

    criteria = [
        ("TJMinusI", "$T_J-i$", "Tisserand parameter with respect to Jupiter", ca_criteria.T_jupiter_i(a, e, inc)),
        ("KMinusI", "$K-i$", "Semimajor-axis--eccentricity criterion", ca_criteria.K_i(a, e, inc)),
        ("QMinusI", "$Q-i$", "Aphelion-distance criterion", ca_criteria.Q_i(a, e, inc)),
        ("EpsilonMinusI", "$\\varepsilon-i$", "Specific-orbital-energy criterion", ca_criteria.E_i(a, inc)),
    ]
    rows = []
    for key, symbol, name, cometary in criteria:
        cometary = np.asarray(cometary, dtype=bool)
        n = int(cometary.size)
        p_comet = float(np.mean(cometary)) if n else np.nan
        rows.append(
            {
                "key": key,
                "symbol": symbol,
                "name": name,
                "n": n,
                "cometary": p_comet,
                "asteroidal": 1.0 - p_comet,
            }
        )
    attrs["n_finite"] = str(int(np.count_nonzero(good)))
    return rows, attrs


def write_table(path: Path = ORBIT_H5, out: Path = OUT) -> None:
    rows, attrs = classify(path)
    lines = [
        "% Generated by reports/generate_orbit_classification_table.py; do not edit by hand.\n",
        f"% trajectory_fit_version: {attrs['trajectory_fit_version']}\n",
        f"% trajectory_json: {attrs['trajectory_json']}\n",
        "\\begin{tabular}{llrr}\n",
        "\\toprule\n",
        f"\\multicolumn{{4}}{{l}}{{Fit version v{attrs['trajectory_fit_version']}; "
        f"{attrs['n_finite']} finite orbit samples}} \\\\\n",
        "\\midrule\n",
        "Criterion & Quantity & Cometary & Asteroidal \\\\\n",
        "\\midrule\n",
    ]
    for row in rows:
        lines.append(
            f"{row['symbol']} & {row['name']} & {fmt_prob(float(row['cometary']))} & {fmt_prob(float(row['asteroidal']))} \\\\\n"
        )
    lines.extend(["\\bottomrule\n", "\\end{tabular}\n"])
    out.write_text("".join(lines), encoding="utf-8")

    macro_lines = [
        "% Generated by reports/generate_orbit_classification_table.py; do not edit by hand.\n",
        latex_macro("OrbitClassificationVersion", attrs["trajectory_fit_version"]),
        latex_macro("OrbitClassificationSampleCount", attrs["n_samples"]),
        latex_macro("OrbitClassificationFiniteSampleCount", attrs["n_finite"]),
        latex_macro("OrbitClassificationSeed", attrs["seed"]),
    ]
    for row in rows:
        key = str(row["key"])
        macro_lines.append(latex_macro(f"OrbitClassification{key}Cometary", fmt_prob(float(row["cometary"]))))
        macro_lines.append(latex_macro(f"OrbitClassification{key}Asteroidal", fmt_prob(float(row["asteroidal"]))))
    MACRO_OUT.write_text("".join(macro_lines), encoding="utf-8")
    print(out)
    print(MACRO_OUT)


if __name__ == "__main__":
    write_table()
