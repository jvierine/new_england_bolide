#!/usr/bin/env python3
from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path

import h5py
import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
FIT_CSV = ROOT / "reports" / "head_echo_python_selection_workflow_ext0p5" / "head_echo_manual_selection_real.csv"
RDMF_DIR = ROOT / "products" / "rdmf_exact_highres_180615_10s_merged_20260602_095431"
OUT = ROOT / "reports" / "head_echo_coherent_timing_table.tex"
EVENT_T0 = 1780164380.0
STATION_LABELS = {
    "beverly": "Beverly",
    "clinton": "Clinton",
    "pomfret": "Pomfret",
}


def fmt_time(unix_time: float) -> str:
    return datetime.fromtimestamp(float(unix_time), UTC).strftime("%H:%M:%S.%f")[:-3]


def station_code_period_s(station: str) -> tuple[float, int, float]:
    path = RDMF_DIR / f"rdmf_peak_{station}_merged.h5"
    with h5py.File(path, "r") as h:
        sample_rate = float(h["sample_rate"][()])
        code_len = int(h["code_len"][()])
    return code_len / sample_rate, code_len, sample_rate


def main() -> None:
    df = pd.read_csv(FIT_CSV)
    df = df[df["selection"].astype(str).str.lower() == "real"].copy()
    if df.empty:
        raise ValueError(f"No real head-echo measurements in {FIT_CSV}")
    df["station"] = df["station"].astype(str)
    df["time_error_s"] = (df["time_unix"] - df["patch_time_unix"]) - 0.5 * df["n_coh"] * df["code_period_s"]
    first_rows = df.sort_values(["station", "time_unix", "idx"]).groupby("station", as_index=False).first()

    code_periods = {station: station_code_period_s(station) for station in sorted(df["station"].unique())}
    code_period = float(np.mean([item[0] for item in code_periods.values()]))
    code_len = int(next(iter(code_periods.values()))[1])
    sample_rate = float(next(iter(code_periods.values()))[2])
    n_coh = int(df["n_coh"].iloc[0])
    step_codes = int(df["step_codes"].iloc[0])
    integration_s = n_coh * code_period
    step_s = step_codes * code_period
    midpoint_s = 0.5 * integration_s
    max_abs_error_us = 1e6 * float(np.nanmax(np.abs(df["time_error_s"])))

    lines = [
        "% Auto-generated by reports/generate_head_echo_timing_table.py\n",
        "\\begin{tabular}{ll}\n",
        "\\toprule\n",
        "Quantity & Value \\\\\n",
        "\\midrule\n",
        f"RF sample rate & {sample_rate / 1000.0:.0f} kHz \\\\\n",
        f"Samples per full code & {code_len:d} \\\\\n",
        f"Full-code period, $T_c$ & {1000.0 * code_period:.1f} ms \\\\\n",
        f"Coherent integration length & {n_coh:d} codes = {1000.0 * integration_s:.0f} ms \\\\\n",
        f"Measurement step & {step_codes:d} code = {1000.0 * step_s:.1f} ms \\\\\n",
        f"Reported measurement time & $t_\\mathrm{{start}} + {1000.0 * midpoint_s:.0f}$ ms \\\\\n",
        f"Maximum CSV midpoint mismatch & {max_abs_error_us:.2f} $\\mu$s \\\\\n",
        "\\bottomrule\n",
        "\\end{tabular}\n",
        "\n",
        "\\vspace{0.75em}\n",
        "\n",
        "\\begin{tabular}{lrrrr}\n",
        "\\toprule\n",
        "Station & Index & Window start & Window end & Reported time \\\\\n",
        " & & (s) & (s) & (s) \\\\\n",
        "\\midrule\n",
    ]
    for row in first_rows.itertuples(index=False):
        start_rel = float(row.patch_time_unix) - EVENT_T0
        report_rel = float(row.time_unix) - EVENT_T0
        end_rel = start_rel + integration_s
        lines.append(
            f"{STATION_LABELS.get(row.station, row.station)} & {int(row.idx)} & {start_rel:.3f} & {end_rel:.3f} & {report_rel:.3f} \\\\\n"
        )
    lines.extend(
        [
            "\\bottomrule\n",
            "\\end{tabular}\n",
        ]
    )
    OUT.write_text("".join(lines), encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    main()
